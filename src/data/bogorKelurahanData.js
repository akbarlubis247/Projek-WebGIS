/**
 * Algoritma Simple Additive Weighting (SAW)
 * Kriteria:
 * - stunting (Benefit: max) -> Semakin tinggi, nilai ternormalisasi semakin tinggi
 * - kemiskinan (Benefit: max) -> Semakin tinggi, nilai ternormalisasi semakin tinggi
 * - kerentananPangan (Benefit: max) -> Semakin tinggi, nilai ternormalisasi semakin tinggi
 * - airBersih (Cost: min) -> Semakin rendah, nilai ternormalisasi semakin tinggi (min / value)
 * 
 * @param {Array} dataList - Daftar kelurahan
 * @param {Object} weights - { stunting: 0.40, kemiskinan: 0.25, kerentananPangan: 0.20, airBersih: 0.15 }
 * @returns {Array} - Data kelurahan lengkap dengan rNilai (normalisasi), skorPreferensi (V), dan zonaPrioritas
 */
export function calculateSAW(dataList, weights = { stunting: 40, kemiskinan: 25, kerentananPangan: 20, airBersih: 15 }) {
  if (!dataList || dataList.length === 0) return [];

  // Normalisasi bobot ke desimal (jumlah bobot total)
  const totalW = (weights.stunting || 0) + (weights.kemiskinan || 0) + (weights.kerentananPangan || 0) + (weights.airBersih || 0) || 100;
  const wStunting = (weights.stunting || 0) / totalW;
  const wKemiskinan = (weights.kemiskinan || 0) / totalW;
  const wPangan = (weights.kerentananPangan || 0) / totalW;
  const wAir = (weights.airBersih || 0) / totalW;

  // 1. Cari nilai Max / Min tiap kriteria
  const maxStunting = Math.max(...dataList.map(d => d.stunting || 0.001));
  const maxKemiskinan = Math.max(...dataList.map(d => d.kemiskinan || 0.001));
  const maxPangan = Math.max(...dataList.map(d => d.kerentananPangan || 0.001));
  const minAir = Math.min(...dataList.map(d => d.airBersih || 0.001));

  // 2. Normalisasi Matriks & Hitung Skor Preferensi V_i
  const calculated = dataList.map((item) => {
    // Normalisasi Benefit: value / max
    const rStunting = maxStunting > 0 ? (item.stunting / maxStunting) : 0;
    const rKemiskinan = maxKemiskinan > 0 ? (item.kemiskinan / maxKemiskinan) : 0;
    const rPangan = maxPangan > 0 ? (item.kerentananPangan / maxPangan) : 0;

    // Normalisasi Cost: min / value
    const rAir = item.airBersih > 0 ? (minAir / item.airBersih) : 0;

    // Nilai Preferensi Vi = SUM(w_j * r_ij)
    const skorPreferensi = (
      (wStunting * rStunting) +
      (wKemiskinan * rKemiskinan) +
      (wPangan * rPangan) +
      (wAir * rAir)
    );

    return {
      ...item,
      rStunting: Number(rStunting.toFixed(3)),
      rKemiskinan: Number(rKemiskinan.toFixed(3)),
      rPangan: Number(rPangan.toFixed(3)),
      rAir: Number(rAir.toFixed(3)),
      skorPreferensi: Number(skorPreferensi.toFixed(4)),
    };
  });

  // 3. Urutkan berdasarkan Skor Preferensi tertinggi (Prioritas Bantuan Utama)
  calculated.sort((a, b) => b.skorPreferensi - a.skorPreferensi);

  // 4. Klasifikasi Zona Prioritas (Merah = Kritis, Kuning = Waspada, Hijau = Aman)
  const total = calculated.length;
  const topCut = Math.ceil(total * 0.25); // Top 25% Zona Merah
  const midCut = Math.ceil(total * 0.65); // 40% Zona Kuning

  return calculated.map((item, index) => {
    const rank = index + 1;
    let zona = 'Hijau (Aman)';
    let zonaClass = 'green';
    let labelPrioritas = 'Prioritas Rendah';

    if (rank <= topCut) {
      zona = 'Merah (Kritis)';
      zonaClass = 'red';
      labelPrioritas = 'Prioritas 1 (Intervensi Utama)';
    } else if (rank <= midCut) {
      zona = 'Kuning (Waspada)';
      zonaClass = 'yellow';
      labelPrioritas = 'Prioritas 2 (Perhatian Khusus)';
    }

    return {
      ...item,
      rank,
      zona,
      zonaClass,
      labelPrioritas,
    };
  });
}
